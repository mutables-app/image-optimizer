// Run after starting npm run dev. Uses real Computer SQLite storage via workerd.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {rgbaPng} from './helpers/png.js';
const base = process.env.WORKER_URL ?? 'http://127.0.0.1:8787';
const input = await readFile(new URL('./fixtures/rgba.png',import.meta.url));
const avif = await readFile(new URL('./fixtures/input-12mp-single.avif',import.meta.url));
const input4k = await readFile(new URL('./fixtures/input-4k.jpg',import.meta.url));
const unsupportedProgressive = await readFile(new URL('./fixtures/input-12mp-arithmetic-progressive.jpg',import.meta.url));
const input8mpHeic = await readFile(new URL('./fixtures/input-8mp-single.heic',import.meta.url));
const input12mpHeic = await readFile(new URL('./fixtures/input-12mp-single.heic',import.meta.url));
const input16mpHeic = await readFile(new URL('./fixtures/input-16mp-single.heic',import.meta.url));
const input24mpHeic = await readFile(new URL('./fixtures/input-24mp-single.heic',import.meta.url));
const input48mpGridHeic = await readFile(new URL('./fixtures/input-48mp-grid.heic',import.meta.url));
const input64mpGridHeic = await readFile(new URL('./fixtures/input-64mp-grid.heic',import.meta.url));
async function request(path, init) {
 const response = await fetch(base+path,init);
 if (!response.ok) throw new Error(`${response.status}: ${await response.text()}`);
 return response;
}
const direct = await request('/optimize?width=8',{method:'POST',body:input});
assert.equal(direct.headers.get('content-type'),'image/webp');
await direct.arrayBuffer();
const jpeg = await request('/optimize?width=8&format=jpeg',{method:'POST',body:input});
assert.equal(jpeg.headers.get('content-type'),'image/jpeg');
const jpegDecoded = spawnSync('python3',['test/decode-image.py'],{input:new Uint8Array(await jpeg.arrayBuffer())});
assert.equal(jpegDecoded.status,0,jpegDecoded.stderr.toString());
assert.deepEqual([JSON.parse(jpegDecoded.stdout).width,JSON.parse(jpegDecoded.stdout).height],[8,4]);
const largeDefault = await request('/optimize?width=800',{method:'POST',body:input4k});
assert.equal(largeDefault.status,200);await largeDefault.arrayBuffer();
const adam7 = rgbaPng(97,65,(x,y)=>[x%256,y%256,128,255],true);
const unsupportedAdam7 = await fetch(base+'/optimize?width=800',{method:'POST',body:adam7});
assert.equal(unsupportedAdam7.status,400);
assert.match((await unsupportedAdam7.json()).error,/Interlaced PNG input is not supported/);
const unsupportedAvif = await fetch(base+'/optimize?width=800',{method:'POST',body:avif});
assert.equal(unsupportedAvif.status,400);
assert.match((await unsupportedAvif.json()).error,/Expected JPEG, PNG or HEIC\/HEIF/);
const unsupportedProgressiveResponse = await fetch(base+'/optimize?width=800',{method:'POST',body:unsupportedProgressive});
assert.equal(unsupportedProgressiveResponse.status,400);
assert.match((await unsupportedProgressiveResponse.json()).error,/Only Lowzag-compatible progressive JPEG is supported/);
const fast = await request('/optimize?width=8&speed=fast',{method:'POST',body:input});
const fastBytes = new Uint8Array(await fast.arrayBuffer());
const largeFast = await request('/optimize?width=800&speed=fast',{method:'POST',body:input4k});
const largeDecoded = spawnSync('python3',['test/decode-webp.py'],{input:new Uint8Array(await largeFast.arrayBuffer())});
assert.equal(largeDecoded.status,0,largeDecoded.stderr.toString());
assert.deepEqual([JSON.parse(largeDecoded.stdout).width,JSON.parse(largeDecoded.stdout).height],[800,450]);
for (const singleImageHeic of [input8mpHeic,input12mpHeic,input16mpHeic,input24mpHeic]) {
 const unsupportedSingleHeic = await fetch(base+'/optimize?width=800',{method:'POST',body:singleImageHeic});
 assert.equal(unsupportedSingleHeic.status,400);
 assert.match((await unsupportedSingleHeic.json()).error,/Non-grid HEIC\/HEIF input is not supported/);
}
const tiledHeicWebp = await request('/optimize?width=800',{method:'POST',body:input48mpGridHeic});
const tiledHeicDecoded = spawnSync('python3',['test/decode-webp.py'],{input:new Uint8Array(await tiledHeicWebp.arrayBuffer())});
assert.equal(tiledHeicDecoded.status,0,tiledHeicDecoded.stderr.toString());
assert.deepEqual([JSON.parse(tiledHeicDecoded.stdout).width,JSON.parse(tiledHeicDecoded.stdout).height],[800,600]);
const tiledHeicJpeg = await request('/optimize?width=800&format=jpeg',{method:'POST',body:input48mpGridHeic});
const tiledHeicJpegDecoded = spawnSync('python3',['test/decode-image.py'],{input:new Uint8Array(await tiledHeicJpeg.arrayBuffer()),maxBuffer:64*1024*1024});
assert.equal(tiledHeicJpegDecoded.status,0,tiledHeicJpegDecoded.stderr.toString());
assert.deepEqual([JSON.parse(tiledHeicJpegDecoded.stdout).width,JSON.parse(tiledHeicJpegDecoded.stdout).height],[800,600]);
const oversizedGrid = await fetch(base+'/optimize?width=800',{method:'POST',body:input64mpGridHeic});
assert.equal(oversizedGrid.status,400);
assert.match((await oversizedGrid.json()).error,/pixel or dimension limit/);
await request('/workspaces/integration/files/input.png',{method:'PUT',body:input});
const result = await request('/workspaces/integration/optimize',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({input:'/input.png',output:'/output.webp',width:8,speed:'fast'})});
assert.equal((await result.json()).path,'/output.webp');
const jpegResult = await request('/workspaces/integration/optimize',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({input:'/input.png',output:'/output.jpg',width:8,format:'jpeg'})});
assert.equal((await jpegResult.json()).contentType,'image/jpeg');
const storedJpeg = await request('/workspaces/integration/files/output.jpg');
assert.equal(storedJpeg.headers.get('content-type'),'image/jpeg');await storedJpeg.arrayBuffer();
const stored = new Uint8Array(await (await request('/workspaces/integration/files/output.webp')).arrayBuffer());
assert.deepEqual(stored,fastBytes);
const checked = spawnSync('python3',['test/decode-webp.py'],{input:stored});
assert.equal(checked.status,0,checked.stderr.toString());
assert.deepEqual([JSON.parse(checked.stdout).width,JSON.parse(checked.stdout).height],[8,4]);
const invalid = await fetch(base+'/optimize',{method:'POST',body:'invalid image'});
assert.equal(invalid.status,400);
const invalidSpeed = await fetch(base+'/optimize?speed=slow',{method:'POST',body:input});
assert.equal(invalidSpeed.status,400);
console.log('PASS: Worker image conversion including Adam7, non-grid HEIC/HEIF, and non-Lowzag progressive JPEG rejection, AVIF rejection, JPEG, 48MP tiled HEIC to WebP/JPEG, 64MP grid rejection, Computer roundtrip, invalid input/options');
